/* Find — web search over detroitautomationacademy.com, built on the
 * two-transfer optima lessons (design: files/find-page/design.md in the
 * rebrand goal workspace).
 *
 * The unit of ranking is the PATH: query -> (middle) -> answer page.
 * Three result kinds, one ranking, no class quarantine:
 *   direct     — the page matches the query itself. One leg.
 *   hub        — the page completes the query after one bridge through
 *                a hub (a section index page), the hub named.
 *   built      — a constructed path: the target does not match the
 *                query directly; the engine constructs a middle —
 *                a Defined Term (concept middle), a page that matches
 *                the query's first concept and links onward (link
 *                middle), or a concept plus the page that carries it
 *                (chain). Built paths are labeled as built.
 *
 * Ranking rules, from the study:
 *   TOTAL COST — every path competes on cost: hops traversed plus the
 *     mismatch of each leg, computed at query time. A built path whose
 *     total cost beats a weak direct result ranks above it.
 *   LOAD-BEARING TEST — a built path surfaces only if removing its
 *     middle leaves the target unreachable: no direct path (the page
 *     covering at least half the query on its own) and no hub path.
 *   CHEAP-BRIDGE RULE — a middle counts only if it is itself a strong
 *     match to the query's first concept and exactly one step from
 *     the target. A weak bridge is not constructed.
 *
 * Everything runs client-side on search-index.json, generated by
 * tools/build-search-index.py from this repository. No external
 * search service, no tracking. The search core is pure so the
 * verification harness runs these exact functions in Node.
 */
'use strict';

/* ---------------- text handling ---------------- */

const STOPWORDS = new Set((
  'a an the and or of to in on for is it its by with at from as are was ' +
  'were be been this that these those i you he she we they my your his ' +
  'her our their what which who whom when where why how do does did ' +
  'can could should would not no if then than too very just about into ' +
  'over under after before between during each other more most some ' +
  'any all but so such only own same'
).split(' '));

function normalizeText(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function stemWord(w) {
  if (w.length > 4 && w.endsWith('ies')) return w.slice(0, -3) + 'y';
  if (w.length > 3 && w.endsWith('s') && !w.endsWith('ss')) return w.slice(0, -1);
  return w;
}

function tokenize(query) {
  const seen = new Set();
  const out = [];
  for (const raw of normalizeText(query).split(' ')) {
    if (!raw || STOPWORDS.has(raw)) continue;
    const t = stemWord(raw);
    if (STOPWORDS.has(t)) continue;
    if (!seen.has(t)) { seen.add(t); out.push(t); }
  }
  return out;
}

function wordSet(norm) {
  const set = new Set();
  if (!norm) return set;
  for (const w of norm.split(' ')) if (w) set.add(stemWord(w));
  return set;
}

function countStem(norm, token) {
  if (!norm) return 0;
  let n = 0;
  for (const w of norm.split(' ')) if (w && stemWord(w) === token) n++;
  return n;
}

/* ---------------- index preparation ---------------- */

function prepareIndex(index) {
  const pages = index.pages.map((p) => {
    const normText = normalizeText(p.text);
    const normTitle = normalizeText(p.title);
    const normHead = normalizeText((p.headings || []).join(' '));
    const normDesc = normalizeText(p.description);
    return {
      url: p.url,
      title: p.title,
      description: p.description || '',
      section: p.section,
      headings: p.headings || [],
      text: p.text || '',
      links: p.links || [],
      hub: !!p.hub,
      normText, normTitle, normHead, normDesc,
      titleWords: wordSet(normTitle),
      headWords: wordSet(normHead),
    };
  });
  const byUrl = new Map(pages.map((p) => [p.url, p]));
  const concepts = (index.concepts || []).map((c) => {
    const normDef = normalizeText(c.definition);
    return {
      term: c.term,
      aliases: c.aliases || [],
      definition: c.definition || '',
      definedIn: c.definedIn,
      definedInTitle: c.definedInTitle || '',
      usedBy: c.usedBy || [],
      termWords: wordSet(normalizeText([c.term].concat(c.aliases || []).join(' '))),
      normDef,
    };
  });
  return { pages, byUrl, concepts, hubs: pages.filter((p) => p.hub) };
}

/* ---------------- scoring ----------------
 * A leg's mismatch is the search analog of scheduled wait: how much of
 * what the leg was asked to carry it fails to carry. Quality combines
 * coverage (the fraction of its tokens matched at all) with a field-
 * weighted score normalized against the best a leg could do. */

const W = { title: 12, heading: 6, desc: 4, body: 1, bodyCap: 12 };
const SCORE_CAP = W.title + W.heading + W.desc + W.bodyCap; // per token: 34
const MISMATCH_SCALE = 60;
const HOP_COST = 7;        // traversing one middle
const CONCEPT_EDGE = 3;    // a concept's structural edge to a page using it
const REACH_COVERAGE = 0.5; // a page "answers" a token set at >= half covered
const COMPLETE_Q = 0.3;     // a target must at least this well complete a split

function quality(score, matched, n) {
  if (!n) return 0;
  const coverage = matched / n;
  const norm = Math.min(score / (SCORE_CAP * n), 1);
  return 0.55 * coverage + 0.45 * norm;
}

function mismatch(score, matched, n) {
  return (1 - quality(score, matched, n)) * MISMATCH_SCALE;
}

function scorePage(p, tokens, phrase) {
  let score = 0;
  let matched = 0;
  const hits = [];
  for (const t of tokens) {
    let s = 0;
    if (p.titleWords.has(t)) s += W.title;
    if (p.headWords.has(t)) s += W.heading;
    if (p.normDesc.includes(t)) s += W.desc;
    s += Math.min(countStem(p.normText, t), W.bodyCap) * W.body;
    if (s > 0) { matched++; hits.push(t); }
    score += s;
  }
  if (tokens.length > 1 && phrase) {
    if (p.normTitle.includes(phrase)) score += 20;
    else if (p.normHead.includes(phrase)) score += 10;
    else if (p.normText.includes(phrase)) score += 5;
  }
  return { score, matched, coverage: tokens.length ? matched / tokens.length : 0, hits };
}

function scoreConcept(c, tokens) {
  let score = 0;
  let matched = 0;
  const hits = [];
  for (const t of tokens) {
    let s = 0;
    if (c.termWords.has(t)) s += W.title;
    if (c.normDef.includes(t)) {
      s += W.heading + Math.min(countStem(c.normDef, t), W.bodyCap) * W.body;
    }
    if (s > 0) { matched++; hits.push(t); }
    score += s;
  }
  return { score, matched, coverage: tokens.length ? matched / tokens.length : 0, hits };
}

/* The cheap-bridge rule: a middle must be a strong match to the part
 * of the query it carries — every token of that part, at real quality.
 * (sc.q and sc.coverage are computed against that part's token set.) */
function isCheapBridge(sc, minScore) {
  return sc.coverage >= 1 && sc.q >= 0.5 && sc.score >= minScore;
}

/* A target completes a split when it covers at least half of the
 * remaining tokens at minimum quality. */
function completesSplit(ps) {
  return ps.coverage >= REACH_COVERAGE && ps.q >= COMPLETE_Q;
}

function makeSnippet(p, rawTokens) {
  const stems = new Set(rawTokens.map(stemWord));
  const text = p.text;
  const words = text.split(/\s+/);
  let hit = -1;
  for (let i = 0; i < words.length; i++) {
    const w = stemWord(normalizeText(words[i]));
    if (w && stems.has(w)) { hit = i; break; }
  }
  if (hit === -1) {
    if (p.description) return p.description;
    return words.slice(0, 28).join(' ') + (words.length > 28 ? '…' : '');
  }
  const start = Math.max(0, hit - 10);
  const end = Math.min(words.length, hit + 18);
  return (start > 0 ? '…' : '') + words.slice(start, end).join(' ') +
    (end < words.length ? '…' : '');
}

/* ---------------- path construction ---------------- */

const MAX_RESULTS = 10;
const KIND_ORDER = { direct: 0, hub: 1, built: 2 };

function legPage(p, why) {
  return { kind: 'page', label: p.title, url: p.url, why };
}

function searchSite(prepared, query) {
  const tokens = tokenize(query);
  if (!tokens.length) return { results: [], tokens, counts: { direct: 0, hub: 0, built: 0 } };
  const phrase = tokens.length > 1 ? normalizeText(query) : '';
  const n = tokens.length;

  const withQ = (sc, subset) => {
    sc.q = quality(sc.score, sc.matched, subset.length);
    return sc;
  };

  /* Score every page against the whole query once. */
  const directInfo = new Map();
  for (const p of prepared.pages) {
    const sc = withQ(scorePage(p, tokens, phrase), tokens);
    directInfo.set(p.url, sc);
  }
  const reachableDirect = (url) => {
    const sc = directInfo.get(url);
    return !!sc && sc.score > 0 && sc.coverage >= REACH_COVERAGE;
  };

  const candidates = [];
  const add = (cand) => candidates.push(cand);

  /* Class 1 — direct. */
  for (const p of prepared.pages) {
    const sc = directInfo.get(p.url);
    if (sc.score > 0) {
      add({
        target: p, kind: 'direct', hops: 0,
        cost: mismatch(sc.score, sc.matched, n),
        legs: [legPage(p, 'Matches your words: ' + sc.hits.join(', '))],
        snippetTokens: tokens,
      });
    }
  }

  /* Splits: a middle carries a first concept; the target completes
   * the rest. Prefix splits serve hub and link middles; concepts may
   * sit anywhere in the query, so they take any contiguous window. */
  const prefixSplits = [];
  for (let k = 1; k < n; k++) prefixSplits.push([tokens.slice(0, k), tokens.slice(k)]);
  const windows = [];
  for (let i = 0; i < n; i++) {
    for (let j = i + 1; j <= n; j++) {
      const a = tokens.slice(i, j);
      const rest = tokens.slice(0, i).concat(tokens.slice(j));
      windows.push([a, rest]);
    }
  }

  /* Class 2 — one bridge through a hub. */
  const hubPaths = new Map(); // target url -> best hub candidate
  for (const h of prepared.hubs) {
    for (const [a, rest] of prefixSplits) {
      const hs = withQ(scorePage(h, a, ''), a);
      if (!isCheapBridge(hs, 8)) continue;
      for (const url of h.links) {
        const p = prepared.byUrl.get(url);
        if (!p || p.url === h.url) continue;
        const ps = withQ(scorePage(p, rest, ''), rest);
        if (!completesSplit(ps)) continue;
        const cand = {
          target: p, kind: 'hub', hops: 1,
          cost: mismatch(hs.score, hs.matched, a.length) +
            mismatch(ps.score, ps.matched, rest.length) + HOP_COST,
          legs: [
            { kind: 'hub', label: h.title, url: h.url, why: 'Hub — collects this series; matches: ' + hs.hits.join(', ') },
            legPage(p, 'Completes your search: ' + ps.hits.join(', ')),
          ],
          middleLabel: h.title,
          snippetTokens: rest,
        };
        const prev = hubPaths.get(p.url);
        if (!prev || cand.cost < prev.cost) hubPaths.set(p.url, cand);
      }
    }
  }
  for (const cand of hubPaths.values()) {
    if (!reachableDirect(cand.target.url)) add(cand);
  }
  const hubReachable = (url) => hubPaths.has(url);

  /* Class 3 — constructed paths. */
  const built = [];
  const addBuilt = (cand) => built.push(cand);

  // Concept middles: the concept carries a window of the query; the
  // target is a page that uses the term (or defines it) and completes
  // whatever the concept did not carry — or, when the concept carried
  // the whole query, the term-usage edge alone completes the journey.
  for (const c of prepared.concepts) {
    for (const [a, rest] of windows) {
      const cs = withQ(scoreConcept(c, a), a);
      if (!isCheapBridge(cs, 6)) continue;
      const targets = new Set(c.usedBy.concat([c.definedIn]));
      for (const url of targets) {
        const p = prepared.byUrl.get(url);
        if (!p) continue;
        const viaDefining = url === c.definedIn && !c.usedBy.includes(url);
        const middle = {
          kind: 'concept', label: c.term, url: c.definedIn,
          why: 'Defined term — its definition matches: ' + cs.hits.join(', ') +
            ' (defined in ' + c.definedInTitle + ')',
        };
        if (!rest.length) {
          addBuilt({
            target: p, kind: 'built', hops: 1,
            cost: mismatch(cs.score, cs.matched, a.length) + HOP_COST + CONCEPT_EDGE,
            legs: [middle, legPage(p, viaDefining
              ? 'The page that defines the term'
              : 'Uses the term “' + c.term + '”')],
            middleLabel: c.term,
            snippetTokens: a,
          });
          continue;
        }
        const ps = withQ(scorePage(p, rest, ''), rest);
        if (completesSplit(ps)) {
          addBuilt({
            target: p, kind: 'built', hops: 1,
            cost: mismatch(cs.score, cs.matched, a.length) +
              mismatch(ps.score, ps.matched, rest.length) + HOP_COST + CONCEPT_EDGE,
            legs: [middle, legPage(p, 'Completes your search: ' + ps.hits.join(', '))],
            middleLabel: c.term,
            snippetTokens: rest,
          });
        }
        // Chain: concept -> this page carrying the term -> a page it
        // links to that completes the rest. The carrier need not
        // complete anything itself; it carries the term onward.
        for (const url2 of p.links) {
          const p2 = prepared.byUrl.get(url2);
          if (!p2 || p2.url === p.url) continue;
          const ps2 = withQ(scorePage(p2, rest, ''), rest);
          if (!completesSplit(ps2)) continue;
          addBuilt({
            target: p2, kind: 'built', hops: 2,
            cost: mismatch(cs.score, cs.matched, a.length) +
              mismatch(ps2.score, ps2.matched, rest.length) +
              2 * HOP_COST + CONCEPT_EDGE,
            legs: [
              middle,
              legPage(p, 'Carries the term onward'),
              legPage(p2, 'Completes your search: ' + ps2.hits.join(', ')),
            ],
            middleLabel: c.term,
            snippetTokens: rest,
          });
        }
      }
    }
  }

  // Link middles: a page matching the first concept, linking onward
  // to the page that completes the query.
  for (const m of prepared.pages) {
    if (m.hub) continue;
    for (const [a, rest] of prefixSplits) {
      const ms = withQ(scorePage(m, a, ''), a);
      if (!isCheapBridge(ms, 12)) continue;
      for (const url of m.links) {
        const p = prepared.byUrl.get(url);
        if (!p || p.url === m.url) continue;
        const ps = withQ(scorePage(p, rest, ''), rest);
        if (!completesSplit(ps)) continue;
        addBuilt({
          target: p, kind: 'built', hops: 1,
          cost: mismatch(ms.score, ms.matched, a.length) +
            mismatch(ps.score, ps.matched, rest.length) + HOP_COST,
          legs: [
            legPage(m, 'Matches your first words: ' + ms.hits.join(', ') + ' — and links onward'),
            legPage(p, 'Completes your search: ' + ps.hits.join(', ')),
          ],
          middleLabel: m.title,
          snippetTokens: rest,
        });
      }
    }
  }

  /* Load-bearing test: a built path surfaces only when its target is
   * unreachable without the middle — no direct path, no hub path. */
  for (const cand of built) {
    if (reachableDirect(cand.target.url)) continue;
    if (hubReachable(cand.target.url)) continue;
    add(cand);
  }

  /* One journey per target: the cheapest legitimate path. Total-cost
   * order across all kinds — no class quarantine. */
  const byTarget = new Map();
  for (const cand of candidates) {
    const prev = byTarget.get(cand.target.url);
    if (!prev || cand.cost < prev.cost ||
      (cand.cost === prev.cost && KIND_ORDER[cand.kind] < KIND_ORDER[prev.kind])) {
      byTarget.set(cand.target.url, cand);
    }
  }
  const results = [...byTarget.values()]
    .sort((x, y) => x.cost - y.cost || x.hops - y.hops ||
      x.target.title.localeCompare(y.target.title))
    .slice(0, MAX_RESULTS)
    .map((cand) => ({
      url: cand.target.url,
      title: cand.target.title,
      section: cand.target.section,
      kind: cand.kind,
      hops: cand.hops,
      cost: Math.round(cand.cost * 10) / 10,
      middleLabel: cand.middleLabel || null,
      legs: cand.legs,
      snippet: makeSnippet(cand.target, cand.snippetTokens),
    }));

  const counts = { direct: 0, hub: 0, built: 0 };
  for (const r of results) counts[r.kind]++;
  return { results, tokens, counts };
}

/* ---------------- browser wiring ---------------- */

if (typeof document !== 'undefined') {
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]));

  function markTerms(text, rawQuery) {
    const terms = tokenize(rawQuery).sort((a, b) => b.length - a.length);
    let out = esc(text);
    for (const t of terms) {
      if (t.length < 2) continue;
      const re = new RegExp('\\b(' + t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\w*)', 'gi');
      out = out.replace(re, '<mark>$1</mark>');
    }
    return out;
  }

  document.addEventListener('DOMContentLoaded', async () => {
    const input = document.getElementById('find-q');
    const box = document.getElementById('find-results');
    const status = document.getElementById('find-status');
    let prepared = null;
    try {
      const res = await fetch('search-index.json');
      prepared = prepareIndex(await res.json());
    } catch (err) {
      status.textContent = 'Search is unavailable right now — the index could not be loaded.';
      return;
    }
    const homeLine = 'Search ' + prepared.pages.length + ' pages, ' +
      prepared.concepts.length + ' defined terms, and ' +
      prepared.hubs.length + ' hubs on this site.';
    status.textContent = homeLine;

    function legLine(leg) {
      const name = leg.url
        ? '<a href="' + leg.url + '">' + esc(leg.label) + '</a>'
        : esc(leg.label);
      return '<li class="find-leg find-leg-' + leg.kind + '"><span class="find-leg-name">' +
        name + '</span> <span class="find-leg-why">' + esc(leg.why) + '</span></li>';
    }

    function render(query) {
      const q = query.trim();
      if (!q) { box.innerHTML = ''; status.textContent = homeLine; return; }
      const { results, counts } = searchSite(prepared, q);
      if (!results.length) {
        status.textContent = 'No matches for “' + q + '”.';
        box.innerHTML =
          '<div class="find-zero">' +
          '<h2>Nothing on the site matches that yet</h2>' +
          '<p>No page on this site matches “' + esc(q) + '”, and no path through ' +
          'a hub or a defined term reaches an answer either. That is an honest ' +
          'zero — nothing was stretched to fit. The hubs are the closest ' +
          'starting points:</p>' +
          '<ul class="find-hubs">' + prepared.hubs.map((h) =>
            '<li><a href="' + h.url + '">' + esc(h.title) + '</a> — ' +
            esc(h.section) + '</li>').join('') +
          '</ul></div>';
        return;
      }
      const parts = [];
      if (counts.direct) parts.push(counts.direct + ' direct');
      if (counts.hub) parts.push(counts.hub + ' through a hub');
      if (counts.built) parts.push(counts.built + ' on a path Find built');
      status.textContent = results.length + (results.length === 1 ? ' journey' : ' journeys') +
        ' for “' + q + '”: ' + parts.join(', ') + '.';
      let html = '';
      if (!counts.direct && !counts.hub) {
        html += '<p class="find-note">Nothing on the site matches that directly — ' +
          'every journey below is one Find built through a middle.</p>';
      }
      html += '<div class="find-cards">';
      for (const r of results) {
        html += '<article class="find-card' + (r.kind === 'built' ? ' find-card-built' : '') + '">' +
          '<p class="find-card-section">' + esc(r.section) + '</p>' +
          '<h3><a href="' + r.url + '">' + esc(r.title) + '</a></h3>';
        if (r.kind === 'direct') {
          html += '<p class="find-route">Direct — one leg.</p>';
        } else {
          html += '<ol class="find-legs">' + r.legs.map(legLine).join('') + '</ol>';
        }
        if (r.kind === 'built') {
          html += '<p class="find-built-label">This page doesn’t use your words. ' +
            'Find built this path — it completes the trip through ' +
            esc(r.middleLabel || 'a middle') + '.</p>';
        } else if (r.kind === 'hub') {
          html += '<p class="find-built-label">Reached through the hub ' +
            esc(r.middleLabel || '') + ' — it collects this series, matched your ' +
            'first words, and this page completes them.</p>';
        }
        html += '<p class="find-snippet">' + markTerms(r.snippet, q) + '</p></article>';
      }
      html += '</div>';
      box.innerHTML = html;
    }

    let timer = null;
    input.addEventListener('input', () => {
      clearTimeout(timer);
      timer = setTimeout(() => render(input.value), 80);
    });
    document.querySelectorAll('[data-find-example]').forEach((btn) => {
      btn.addEventListener('click', () => {
        input.value = btn.getAttribute('data-find-example');
        render(input.value);
        input.focus();
      });
    });
    const initial = new URLSearchParams(location.search).get('q');
    if (initial) { input.value = initial; render(initial); }
  });
}

